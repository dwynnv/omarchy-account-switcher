# account-switcher: the config file (~/.config/account-switcher/config.json) and the files `account-switcher
# setup` derives from it (lib/config.jq does the work). Sourced by bin/account-switcher after
# lib/mode.bash.

dm_catalog_path() { printf '%s\n' "$DM_PLUGIN/catalog.json"; }

# The gh that git's credential helpers run (tests set ACCOUNT_SWITCHER_GH, "" for none). A gh inside
# a mise install sits in a versioned folder that its next update replaces: mise's shim instead.
config_gh() {
  local gh shim
  if [[ -n ${ACCOUNT_SWITCHER_GH+x} ]]; then
    printf '%s\n' "$ACCOUNT_SWITCHER_GH"
    return
  fi
  gh=$(command -v gh 2>/dev/null)
  if [[ $gh == */mise/installs/* ]]; then
    shim=${gh%%/mise/installs/*}/mise/shims/gh
    [[ -x $shim ]] && gh=$shim
  fi
  printf '%s\n' "$gh"
}

# config_jq errors|derive FILE: run lib/config.jq over FILE and the catalog.
config_jq() {
  jq -nj --arg what "$1" --slurpfile cfg "$2" --slurpfile cat "$(dm_catalog_path)" \
    --arg home "$HOME" --arg data "$(dm_data_dir)" --arg gh "$(config_gh)" --arg cfgpath "${2/#"$HOME"/\~}" \
    -f "$DM_PLUGIN/lib/config.jq"
}

# config_check [FILE]: one "account-switcher config: <field>: <problem>" line per problem on stderr;
# status 1 when there is any.
config_check() {
  local file=${1:-$(dm_config_path)} out
  if [[ ! -e $file ]]; then
    echo "account-switcher config: config.json: missing at $file (copy $DM_PLUGIN/config.example.json there and edit it)" >&2
    return 1
  fi
  if ! out=$(jq empty "$file" 2>&1); then
    echo "account-switcher config: config.json: not valid JSON (${out##*: })" >&2
    return 1
  fi
  if ! out=$(jq -nr --arg what errors --slurpfile cfg "$file" --slurpfile cat "$(dm_catalog_path)" \
    --arg home "$HOME" --arg data "" --arg gh "" --arg cfgpath "" -f "$DM_PLUGIN/lib/config.jq" 2>&1); then
    echo "account-switcher config: config.json: couldn't be checked (${out##*: })" >&2
    return 1
  fi
  [[ -z $out ]] && return 0
  sed 's/^/account-switcher config: /' <<<"$out" >&2
  return 1
}

# The global git file of MODE's terminals (their GIT_CONFIG_GLOBAL): made once, then the user's,
# so `git config --global` there sticks. Git's own files first, the mode's identity last.
git_global_text() {
  local label=${1^}
  printf '%s\n' "# $label terminals' global git config, made once by account-switcher setup and then yours:" \
    "# \`git config --global\` in a $label terminal writes here. Git's own files come first, then the" \
    "# $label identity, which setup keeps up to date in account-switcher-$1.inc." \
    '[include]' $'\tpath = config' $'\tpath = ~/.gitconfig' $'\tpath = account-switcher-'"$1"'.inc'
}

# config_apply: check the config, then write config.bash, apps and hold.json (state folder) and
# the identity files the modes' global git files include (~/.config/git), making those once.
# Every file is written next to its target first and only then renamed, so a failure leaves the
# old set; an unchanged file keeps its old copy. A file of the user's own where an identity file
# goes stops it before any change. Sets DM_APPS_CHANGED=1 when the Hyprland side's rules changed.
DM_APPS_CHANGED=0
config_apply() {
  local file state git tmp name i m
  file=$(dm_config_path)
  config_check "$file" || return 1
  state=$(dm_state_dir) git=${XDG_CONFIG_HOME:-$HOME/.config}/git
  tmp=$(mktemp -d) || return 1
  local -a moves=() theirs=()
  if config_jq derive "$file" >"$tmp/derived.json"; then
    while IFS= read -r name; do
      [[ -e $git/$name ]] && ! head -n1 "$git/$name" | grep -q '^# Generated by account-switcher setup' && theirs+=("$git/$name")
    done < <(jq -r '.git | keys[]' "$tmp/derived.json")
  fi
  if ((${#theirs[@]})); then
    rm -rf "$tmp"
    printf 'account-switcher: %s is a file of your own, not one setup made; move it away and run setup again. Nothing changed.\n' \
      "${theirs[@]/#"$HOME"/\~}" >&2
    return 1
  fi
  if [[ -s $tmp/derived.json ]] && mkdir -p "$state" "$git"; then
    for name in config.bash apps hold.json; do
      jq -j --arg k "$name" '.[$k]' "$tmp/derived.json" >"$state/.$name.new" || break
      moves+=("$state/.$name.new" "$state/$name")
    done
    while IFS= read -r name; do
      jq -j --arg k "$name" '.git[$k]' "$tmp/derived.json" >"$git/.$name.new" || break
      moves+=("$git/.$name.new" "$git/$name")
    done < <(jq -r '.git | keys[]' "$tmp/derived.json")
  fi
  if ((${#moves[@]} != 2 * (3 + $(jq '.git | length' "$tmp/derived.json" 2>/dev/null || echo 99)))); then
    for ((i = 0; i < ${#moves[@]}; i += 2)); do rm -f "${moves[i]}"; done
    rm -rf "$tmp"
    echo "account-switcher: setup couldn't write its files; nothing changed" >&2
    return 1
  fi
  rm -rf "$tmp"
  DM_APPS_CHANGED=0
  for ((i = 0; i < ${#moves[@]}; i += 2)); do
    if cmp -s "${moves[i]}" "${moves[i + 1]}"; then
      rm -f "${moves[i]}"
      continue
    fi
    [[ ${moves[i + 1]} == "$state/apps" ]] && DM_APPS_CHANGED=1
    mv -f "${moves[i]}" "${moves[i + 1]}"
  done
  for m in work personal; do
    if [[ ! -e $git/account-switcher-$m ]]; then
      git_global_text "$m" >"$git/account-switcher-$m"
    elif ! git config -f "$git/account-switcher-$m" --get-all include.path 2>/dev/null | grep -qxF "account-switcher-$m.inc"; then
      echo "account-switcher: ${git/#"$HOME"/\~}/account-switcher-$m doesn't include account-switcher-$m.inc, so ${m^} terminals miss the ${m^} identity" >&2
    fi
  done
  return 0
}

# The folders the config names, made once (never the home folder itself).
config_make_folders() {
  local m kind dir
  for m in work personal; do
    for kind in HOME AGENT FILES SHOTS RECS DOWNLOADS; do
      dir=DM_${kind}_$m
      dir=${!dir-}
      [[ -n $dir && $dir != "$HOME" ]] && mkdir -p "$dir"
    done
  done
  return 0
}
