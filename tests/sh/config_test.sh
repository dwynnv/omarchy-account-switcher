#!/usr/bin/env bash
# The config file (~/.config/account-switcher/config.json) and what `account-switcher setup` derives
# from it, against a scratch HOME with the example config.
cd "$(dirname "$0")" || exit 1
source ./t.bash
PLUGIN=$(cd ../.. && pwd)
DM=$PLUGIN/bin/account-switcher
TMP=${TEST_TMPDIR:?run through tests/run.sh}/config
export ACCOUNT_SWITCHER_WALK_ROOT=$$

fresh() {
  rm -rf "$TMP"
  mkdir -p "$TMP/home/.config/account-switcher" "$TMP/fakes"
  export HOME=$TMP/home ACCOUNT_SWITCHER_RUN_LOG=$TMP/run.log ACCOUNT_SWITCHER_FAKES=$TMP/fakes ACCOUNT_SWITCHER_GH=/opt/gh/bin/gh
  unset XDG_STATE_HOME XDG_DATA_HOME XDG_CONFIG_HOME ACCOUNT_SWITCHER_MODE HYPRLAND_INSTANCE_SIGNATURE
  cp "$PLUGIN/tests/fixtures/config.test.json" "$HOME/.config/account-switcher/config.json"
  : >"$ACCOUNT_SWITCHER_RUN_LOG"
}
STATE() { echo "$HOME/.local/state/account-switcher"; }
CFG() { echo "$HOME/.config/account-switcher/config.json"; }
GIT() { echo "$HOME/.config/git"; }
edit() { jq "$1" "$(CFG)" >"$(CFG).new" && mv "$(CFG).new" "$(CFG)"; }

t_example() {
  fresh
  "$DM" setup >/dev/null
  t_eq $? 0
  t_ok "$DM" config check
  t_eq "$("$DM" config path)" "$HOME/.config/account-switcher/config.json"
  source "$(STATE)/config.bash"
  t_eq "$DM_CONFIGURED" 1
  t_eq "$DM_LOGIN_work" alex-work
  t_eq "$DM_LOGIN_personal" alex
  t_eq "$DM_HOME_work" "$HOME/Work"
  t_eq "$DM_HOME_personal" "$HOME"
  t_eq "$DM_AGENT_personal" "$HOME/Projects"
  t_eq "$DM_FILES_personal" "$HOME"
  t_eq "$DM_SHOTS_work" "$HOME/Work/Pictures"
  t_eq "$DM_SHOTS_personal" ""
  t_eq "$DM_DOWNLOADS_work" "$HOME/Work/Downloads"
  t_eq "$DM_BROWSER_work" google-chrome
  t_eq "$DM_BROWSER_BIN_personal" /usr/bin/chromium
  t_eq "$DM_BROWSER_CLASS_work" google-chrome
  t_eq "$DM_BROWSER_EXEDIR_work" /opt/google/chrome/
  t_eq "${DM_APP_MODE[slack]}" work
  t_eq "${DM_APP_MODE[steam]}" personal
  t_eq "${DM_APP_BIN[slack]}" /usr/bin/slack
  t_eq "${DM_APP_DESKTOP[steam]}" steam.desktop
  t_eq "${DM_APP_EXEC[slack]}" /usr/bin/slack
  t_eq "${DM_APP_FOCUS[slack]}" 0
  t_eq "${DM_ROUTE_BROWSERS[*]}" "personal chromium.desktop chromium"
  t_eq "${DM_OWNER_EMAIL[alex-work]}" alex@work.example
  t_eq "${DM_OWNER_EMAIL[work-org]}" alex@work.example
  t_eq "${DM_OWNER_EMAIL[alex]}" alex@home.example
  t_eq "${DM_OWNER_EMAIL[side-org]}" alex@side.example
  t_eq "${DM_OWNER_LOGIN[work-org]}" alex-work
  t_eq "${DM_OWNER_LOGIN[side-org]}" alex-side
  t_eq "${DM_EMAIL_MODE[alex@side.example]}" personal
  t_eq "${DM_EMAIL_MODE[alex@work.example]}" work
  t_eq "$DM_OWN_EMAILS" " alex@work.example alex@home.example alex@side.example "
  t_eq "${DM_ACCOUNTS[*]}" "side-org personal alex-side"
  t_eq "${DM_WEBAPP_MODE[WhatsApp]}" personal
  t_eq "${DM_WEBAPP_MODE[Google Messages]}" personal
  t_eq "${DM_WEBAPP_MODE[YouTube]}" follow
  t_eq "$DM_CLOCK_APPS" "slack browser code"
  t_eq "$DM_MAILTO" gmail
  t_eq "$DM_GH" /opt/gh/bin/gh
  # The folders exist after setup.
  t_ok test -d "$HOME/Work/Pictures"
  t_ok test -d "$HOME/Work/Downloads"
  t_ok test -d "$HOME/Projects"
}
t_test "the example config derives the shell variables, and setup makes the folders" t_example

t_apps_file() {
  fresh
  "$DM" setup >/dev/null
  local f
  f=$(STATE)/apps
  local line
  for line in 'exe work /opt/google/chrome/' 'exe personal /usr/lib/chromium/' 'class work google-chrome' \
    'class personal chromium' 'class work slack' 'class personal steam' 'prefix personal steam_app_' \
    'browser google-chrome' 'browser chromium' 'home slack' 'home steam' 'home-prefix steam_app_' \
    'place slack' 'place google-chrome' 'place com.microsoft.vscode'; do
    t_ok grep -qxF "$line" "$f"
  done
  t_none '^place steam' "$f"
  t_eq "$(grep -cv '^#' "$f")" 15
}
t_test "the Hyprland side's rules: browsers, apps, prefixes and the places clock-in remembers" t_apps_file

t_hold() {
  fresh
  "$DM" setup >/dev/null
  t_eq "$(jq -c '.names' "$(STATE)/hold.json")" '["slack","google chrome"]'
  t_eq "$(jq -c '.entries' "$(STATE)/hold.json")" '["slack","google-chrome"]'
  edit '.holdApps = ["Example VPN"]'
  "$DM" setup >/dev/null
  t_eq "$(jq -c '.names' "$(STATE)/hold.json")" '["slack","google chrome","example vpn"]'
}
t_test "what waits in Personal: the Work apps, the Work browser and the extra names" t_hold

t_git() {
  fresh
  "$DM" setup >/dev/null
  local g d
  g=$(GIT) d=$HOME/.local/share/account-switcher/gh
  # The mode's global git file: git's own files, in git's order, then the identity setup keeps
  # up to date in its own file (which wins).
  t_eq "$(git config -f "$g/account-switcher-work" --get-all include.path | tr '\n' ' ')" "config ~/.gitconfig account-switcher-work.inc "
  t_eq "$(git config -f "$g/account-switcher-personal" --get-all include.path | tr '\n' ' ')" "config ~/.gitconfig account-switcher-personal.inc "
  t_ok grep -qx '# Generated by account-switcher setup from .*; edits are overwritten\.' "$g/account-switcher-work.inc"
  t_eq "$(git config -f "$g/account-switcher-work.inc" user.name)" "Alex Example"
  t_eq "$(git config -f "$g/account-switcher-work.inc" user.email)" alex@work.example
  t_eq "$(git config -f "$g/account-switcher-work.inc" --get-all credential.https://github.com.helper | head -n1)" ""
  t_eq "$(git config -f "$g/account-switcher-work.inc" --get-all credential.https://github.com.helper | tail -n1)" \
    "!GH_CONFIG_DIR=$d/alex-work /opt/gh/bin/gh auth git-credential"
  t_eq "$(git config -f "$g/account-switcher-work.inc" --get-all credential.https://gist.github.com.helper | tail -n1)" \
    "!GH_CONFIG_DIR=$d/alex-work /opt/gh/bin/gh auth git-credential"
  t_none 'includeIf' "$g/account-switcher-work.inc"
  t_eq "$(git config -f "$g/account-switcher-personal.inc" "includeIf.gitdir:$HOME/Side/.path")" account-switcher-owner-side-org.inc
  t_eq "$(git config -f "$g/account-switcher-personal.inc" --get-all credential.https://github.com/side-org.helper | tail -n1)" \
    "!GH_CONFIG_DIR=$d/alex-side /opt/gh/bin/gh auth git-credential"
  t_eq "$(git config -f "$g/account-switcher-owner-side-org.inc" user.email)" alex@side.example
  # A name git would misread unquoted is quoted.
  edit '.work.git.name = "Alex \"AJ\" Example; Jr"'
  "$DM" setup >/dev/null
  t_eq "$(git config -f "$g/account-switcher-work.inc" user.name)" 'Alex "AJ" Example; Jr'
}
t_test "each mode's git file: identity, the side account's folder and the credential helpers" t_git

t_git_not_ours() {
  fresh
  mkdir -p "$(GIT)"
  printf '[user]\n\temail = mine@example.com\n' >"$(GIT)/account-switcher-work.inc"
  local err
  err=$("$DM" setup 2>&1 >/dev/null) && t_eq ok refused "setup over a git file it didn't make"
  t_ok grep -qF 'account-switcher-work.inc' <<<"$err"
  t_eq "$(git config -f "$(GIT)/account-switcher-work.inc" user.email)" mine@example.com
  t_ok test ! -e "$(STATE)/config.bash"
}
t_test "a file of the user's own where setup writes a git file is never replaced" t_git_not_ours

t_no_gh() {
  fresh
  ACCOUNT_SWITCHER_GH='' "$DM" setup >/dev/null
  t_eq $? 0
  t_none 'credential' "$(GIT)/account-switcher-work.inc"
  t_eq "$(git config -f "$(GIT)/account-switcher-work.inc" user.email)" alex@work.example
  source "$(STATE)/config.bash"
  t_eq "$DM_GH" ""
  # A mode without a login gets no helper either.
  fresh
  edit 'del(.work.github)'
  "$DM" setup >/dev/null
  t_none 'credential' "$(GIT)/account-switcher-work.inc"
}
t_test "without gh, or without a login, the git files have no credential helpers" t_no_gh

t_gh_path() {
  fresh
  unset ACCOUNT_SWITCHER_GH
  # gh found inside a mise install (a versioned folder): its shim, which survives updates.
  local inst=$HOME/.local/share/mise/installs/gh/9.9.9/bin shim=$HOME/.local/share/mise/shims
  mkdir -p "$inst" "$shim"
  printf '#!/bin/sh\n' >"$inst/gh" && printf '#!/bin/sh\n' >"$shim/gh" && chmod +x "$inst/gh" "$shim/gh"
  PATH=$inst:$PATH "$DM" setup >/dev/null
  source "$(STATE)/config.bash"
  t_eq "$DM_GH" "$shim/gh"
  # Anywhere else: that gh.
  local own=$TMP/bin
  mkdir -p "$own" && printf '#!/bin/sh\n' >"$own/gh" && chmod +x "$own/gh"
  PATH=$own:$PATH "$DM" setup >/dev/null
  source "$(STATE)/config.bash"
  t_eq "$DM_GH" "$own/gh"
}
t_test "the gh in the credential helpers is one that stays put" t_gh_path

t_invalid() {
  local filter field err rc
  while IFS='|' read -r filter field; do
    fresh
    case $filter in
      MISSING) rm -f "$(CFG)" ;;
      TEMPLATE) cp "$PLUGIN/config.example.json" "$(CFG)" ;;
      BADJSON) echo '{"work":' >"$(CFG)" ;;
      *) edit "$filter" ;;
    esac
    err=$("$DM" setup 2>&1 >/dev/null)
    rc=$?
    t_eq "$rc" 1 "$filter"
    t_ok grep -q '^account-switcher config: ' <<<"$err"
    t_ok grep -qF "$field" <<<"$err"
    t_ok test ! -e "$(STATE)/config.bash"
    t_ok test ! -e "$(GIT)/account-switcher-work.inc"
  done <<'EOF'
MISSING|config.json
TEMPLATE|work.git.email: still the example's
TEMPLATE|personal.github: still the example's
BADJSON|config.json
.work.browser = "netscape"|work.browser
del(.personal.browser)|personal.browser
.personal.browser = "google-chrome"|personal.browser
.personal.apps += ["slack"]|personal.apps
.work.apps = ["nope"]|work.apps
.work.git.email = "nobody"|work.git.email
.work.github = "not a login"|work.github
.mailto = "x"|mailto
.accounts[0].github = ""|accounts[0].github
.accounts[0].mode = "home"|accounts[0].mode
.work.folders.home = 7|work.folders.home
.clockInApps = ["nope"]|clockInApps
.clockInApps = ["steam"]|clockInApps
.customApps.foo = {"class": "foo"}|customApps.foo
.work.githubOwner = ["work-org"]|work.githubOwner: unknown key
.colour = 1|colour: unknown key
.work.folders.dowloads = "~/D"|work.folders.dowloads: unknown key
.work.git.mail = "x@y"|work.git.mail: unknown key
.accounts[0].foldr = "~/S"|accounts[0].foldr: unknown key
EOF
}
t_test "a missing or broken config is refused, field by field, and nothing is written" t_invalid

