t_custom() {
  fresh
  edit '.customApps.foo = {"label": "Foo", "bin": "/usr/bin/foo", "class": "Foo", "desktop": "foo.desktop", "execToken": "foo", "notify": ["Foo"], "notifyEntries": ["foo"]}
    | .customBrowsers.brave = {"label": "Brave", "bin": "/usr/bin/brave", "exeDir": "/opt/brave-bin/", "class": "brave-browser", "desktop": "brave-browser.desktop", "execToken": "brave", "routeDesktop": true, "notify": ["Brave"], "notifyEntries": ["brave-browser"]}
    | .work.apps += ["foo"] | .personal.browser = "brave" | del(.clockInApps)'
  "$DM" setup >/dev/null
  t_eq $? 0
  t_ok grep -qxF 'class work foo' "$(STATE)/apps"
  t_ok grep -qxF 'home foo' "$(STATE)/apps"
  t_ok grep -qxF 'exe personal /opt/brave-bin/' "$(STATE)/apps"
  source "$(STATE)/config.bash"
  t_eq "${DM_APP_BIN[foo]}" /usr/bin/foo
  t_eq "${DM_APP_CLASS[foo]}" foo
  t_eq "$DM_BROWSER_BIN_personal" /usr/bin/brave
  t_eq "${DM_ROUTE_BROWSERS[*]}" "personal brave-browser.desktop brave"
  t_eq "$DM_CLOCK_APPS" "slack foo browser"
  t_eq "$(jq -c '.names' "$(STATE)/hold.json")" '["slack","foo","google chrome"]'
}
t_test "custom browsers and apps from the config work like built-in ones" t_custom

